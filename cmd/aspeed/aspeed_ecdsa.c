static int ecdsa_msg_sha(struct ecdsa_ts *ts, uint8_t *digest, int len)
{
	struct hash_algo *algo = NULL;

	if (len < ts->digest_len) {
		printf("[ecdsa_kat] Digest buffer insufficient.\n");
		return CMD_RET_FAILURE;
	}

	if (hash_lookup_algo(ts->digest_algo, &algo)) {
		printf("[ecdsa_kat] Unsupported hash algorithm\n");
		return CMD_RET_FAILURE;
	}

	if (ts->digest_len != algo->digest_size) {
		printf("[ecdsa_kat] Invalid test case\n");
		return CMD_RET_FAILURE;
	}

	algo->hash_func_ws(ts->msg, ts->msg_len, digest, algo->chunk_size);

	return 0;
}

static int ecdsa_verify_kat(struct ecdsa_ts *ts)
{
	uint8_t hash[64] = { 0 };
	int ret = 0;
	const struct ecdsa_ops *ops;
	struct udevice *dev;
	struct ecdsa_public_key pubkey = {
		.curve_name = ts->curve,
		.size_bits = ts->sig_len << 3,
		.x = ts->qx,
		.y = ts->qy,
	};

	ret = ecdsa_msg_sha(ts, hash, sizeof(hash));
	if (ret) {
		printf("aspeed_ecdsa verify_kat: failed to hash message\n");
		return CMD_RET_FAILURE;
	}

	ret = uclass_get_device_by_driver(UCLASS_ECDSA,
					  DM_DRIVER_GET(aspeed_ecdsa), &dev);
	if (ret) {
		printf("aspeed_ecdsa device not found: %d\n", ret);
		return CMD_RET_FAILURE;
	}

	ops = device_get_ops(dev);
	if (!ops || !ops->verify) {
		printf("aspeed_ecdsa device has no verify op\n");
		return CMD_RET_FAILURE;
	}

	ret = ops->verify(dev, &pubkey, hash, ts->digest_len, ts->sig,
			  2 * ts->sig_len);
	if ((ret == 0 && ts->result) || (ret != 0 && !ts->result))
		return 0;
	else
		return -1;
}

static int do_ecdsa_verify_kat(struct cmd_tbl *cmdtp, int flag, int argc,
			       char *const argv[])
{
	bool result = true;
	int i = 0;
	int ret = 0;

	printf("ECDSA KAT P-256 test:\n");
	for (i = 0; i < ARRAY_SIZE(kat_nist_186_4_p256); i++) {
		ret = ecdsa_verify_kat(&kat_nist_186_4_p256[i]);
		printf("ECDSA P-256 [%d] digest_len %d: %s\n", i,
		       kat_nist_186_4_p256[i].digest_len,
		       !ret ? "pass" : "fail");

		result &= !ret ? true : false;
	}

	printf("ECDSA KAT P-384 test:\n");
	for (i = 0; i < ARRAY_SIZE(kat_nist_186_4_p384); i++) {
		ret = ecdsa_verify_kat(&kat_nist_186_4_p384[i]);
		printf("ECDSA P-384 [%d] digest_len %d: %s\n", i,
		       kat_nist_186_4_p384[i].digest_len,
		       !ret ? "pass" : "fail");

		result &= !ret ? true : false;
	}

	return result ? CMD_RET_SUCCESS : CMD_RET_FAILURE;
}

static struct cmd_tbl ecdsa_commands[] = {
	U_BOOT_CMD_MKENT(verify_kat, 1, 1, do_ecdsa_verify_kat, "", ""),
};

static int do_ecdsa(struct cmd_tbl *cmdtp, int flag, int argc,
		    char *const argv[])
{
	struct cmd_tbl *ecdsa_cmd;
	int ret;

	if (argc < 2)
		return CMD_RET_USAGE;

	ecdsa_cmd = find_cmd_tbl(argv[1], ecdsa_commands,
				 ARRAY_SIZE(ecdsa_commands));
	argc -= 1;
	argv += 1;
	if (!ecdsa_cmd || argc > ecdsa_cmd->maxargs || argc < 1)
		return CMD_RET_USAGE;

	ret = ecdsa_cmd->cmd(ecdsa_cmd, flag, argc, argv);

	return cmd_process_error(ecdsa_cmd, ret);
}

