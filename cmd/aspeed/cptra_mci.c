static int cptra_mci_sha_test_one(enum HASH_ALGO algo, const char *label,
				  const u8 *expected, size_t expected_len)
{
	u8 digest[CPTRA_MCI_SHA512_DIGEST_SIZE];
	struct udevice *dev;
	int ret;

	ret = uclass_get_device_by_driver(UCLASS_HASH, DM_DRIVER_GET(aspeed_cptra_mci_sha), &dev);
	if (ret) {
		printf("%s: cptra_mci_sha device not found: %d\n", label, ret);
		return ret;
	}

	ret = hash_digest(dev, algo, "abc", 3, digest);
	if (ret) {
		printf("%s: hash_digest failed: %d\n", label, ret);
		return ret;
	}

	if (memcmp(digest, expected, expected_len) != 0) {
		printf("%s: FAIL (digest does not match known-answer vector)\n", label);
		return -EIO;
	}

	printf("%s: PASS\n", label);

	return 0;
}

