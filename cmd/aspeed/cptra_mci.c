	ret = cptra_mci_reg_print("CPTRA_TRNG_VALID_AXI_USER", CPTRA_MCI_SOC_IFC_PAGE,
				  CPTRA_MCI_SOC_IFC_CPTRA_TRNG_VALID_AXI_USER);
