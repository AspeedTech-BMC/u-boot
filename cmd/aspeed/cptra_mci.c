static int do_cptra_mci_fw_version(struct cmd_tbl *cmdtp, int flag,
				   int argc, char *const argv[])
{
	static const enum cptra_mci_fw_index indexes[] = {
		CPTRA_MCI_FW_INDEX_CALIPTRA_CORE,
		CPTRA_MCI_FW_INDEX_MCU_RUNTIME,
		CPTRA_MCI_FW_INDEX_SOC,
	};
	char version[CPTRA_MCI_MAX_FW_VERSION_STR_LEN + 1];
	size_t i;
	int ret;

	for (i = 0; i < ARRAY_SIZE(indexes); i++) {
		ret = cptra_mci_get_firmware_version(indexes[i], version, sizeof(version));
		if (ret) {
			printf("MC_FIRMWARE_VERSION (index %d) failed: %d\n", indexes[i], ret);
			return CMD_RET_FAILURE;
		}

		printf("index %d: %s\n", indexes[i], version);
	}

	return CMD_RET_SUCCESS;
}

/*
 * Dump of the Caliptra-SS subsystem status registers (mci_reg and
 * soc_ifc_reg blocks) via cptra_mci_reg_read() -- plain memory-mapped
 * register reads through the paged SCU1 window, not mailbox protocol
 * commands. See the comment on the CPTRA_MCI_REG_* / CPTRA_MCI_SOC_IFC_*
 * definitions in cptra_mci_mbox.h.
 */
/* Section header: page is shown once here instead of on every register line. */
static void cptra_mci_reg_section(const char *name, u32 page)
{
	printf("\n== %s (page 0x%04x) ==\n", name, page);
}

static int cptra_mci_reg_print(const char *label, u32 page, u32 offset)
{
	u32 value;
	int ret;

	ret = cptra_mci_reg_read(page, offset, &value);
	if (ret) {
		printf("  %-30s 0x%04x  read failed: %d\n", label, offset, ret);
		return ret;
	}

	printf("  %-30s 0x%04x = 0x%08x\n", label, offset, value);

	return 0;
}

static int cptra_mci_reg_print_array(const char *label, u32 page, u32 (*offset_fn)(u32 n),
				     u32 count)
{
	char name[40];
	u32 i;
	int ret;

	for (i = 0; i < count; i++) {
		snprintf(name, sizeof(name), "%s[%u]", label, i);

		ret = cptra_mci_reg_print(name, page, offset_fn(i));
		if (ret)
			return ret;
	}

	return 0;
}

/* Bit-field sub-line, indented further than the register line it belongs to. */
static void cptra_mci_reg_field_print(const char *name, u32 value)
{
	printf("        %-20s = %u\n", name, value);
}

