static int do_cptra_mci_ecdsa_verify_test(struct cmd_tbl *cmdtp, int flag,
					  int argc, char *const argv[])
{
	/* All-zero seed: pubkey is then the known, fixed value above. */
	static const u8 seed[CPTRA_MCI_ECC384_SCALAR_SIZE];
	static u8 message[CPTRA_MCI_ECC384_SCALAR_SIZE];
	u8 cmk[CPTRA_MCI_CMK_SIZE];
	u8 qx[CPTRA_MCI_ECC384_SCALAR_SIZE], qy[CPTRA_MCI_ECC384_SCALAR_SIZE];
	u8 sig[2 * CPTRA_MCI_ECC384_SCALAR_SIZE];
	u8 hash[CPTRA_MCI_SHA384_DIGEST_SIZE], bad_hash[CPTRA_MCI_SHA384_DIGEST_SIZE];
	struct ecdsa_public_key pubkey = {
		.curve_name = "secp384r1",
		.size_bits = CPTRA_MCI_ECC384_SCALAR_SIZE << 3,
		.x = qx,
		.y = qy,
	};
	const struct ecdsa_ops *ops;
	struct udevice *ecdsa_dev, *sha_dev;
	int ret, i;

	ret = cptra_mci_import_key(CPTRA_MCI_KEY_USAGE_ECDSA, seed, sizeof(seed), cmk);
	if (ret) {
		printf("MC_IMPORT failed: %d\n", ret);
		return CMD_RET_FAILURE;
	}

	ret = cptra_mci_ecdsa_cmk_public_key(cmk, qx, qy);
	if (ret) {
		printf("MC_ECDSA_CMK_PUBLIC_KEY failed: %d\n", ret);
		return CMD_RET_FAILURE;
	}

	if (memcmp(qx, cptra_mci_ecdsa_test_pubkey_x, sizeof(qx)) != 0 ||
	    memcmp(qy, cptra_mci_ecdsa_test_pubkey_y, sizeof(qy)) != 0) {
		printf("MC_ECDSA_CMK_PUBLIC_KEY: FAIL (public key mismatch)\n");
		return CMD_RET_FAILURE;
	}
	printf("MC_ECDSA_CMK_PUBLIC_KEY: PASS (matches known-answer vector)\n");

	for (i = 0; i < (int)sizeof(message); i++)
		message[i] = i;

	ret = cptra_mci_ecdsa_cmk_sign(cmk, message, sizeof(message), sig,
				       sig + CPTRA_MCI_ECC384_SCALAR_SIZE);
	if (ret) {
		printf("MC_ECDSA_CMK_SIGN failed: %d\n", ret);
		return CMD_RET_FAILURE;
	}

	/*
	 * MC_ECDSA_CMK_SIGN hashed `message` internally before signing, but
	 * MC_ECDSA384_SIG_VERIFY takes an already-hashed digest with no
	 * further hashing -- hash the same bytes here before handing them to
	 * the raw-pubkey verify below.
	 */
	ret = uclass_get_device_by_driver(UCLASS_HASH, DM_DRIVER_GET(aspeed_cptra_mci_sha),
					  &sha_dev);
	if (ret) {
		printf("cptra_mci_sha device not found: %d\n", ret);
		return CMD_RET_FAILURE;
	}

	ret = hash_digest(sha_dev, HASH_ALGO_SHA384, message, sizeof(message), hash);
	if (ret) {
		printf("hash_digest failed: %d\n", ret);
		return CMD_RET_FAILURE;
	}

	ret = uclass_get_device_by_driver(UCLASS_ECDSA, DM_DRIVER_GET(aspeed_cptra_mci_ecdsa),
					  &ecdsa_dev);
	if (ret) {
		printf("cptra_mci_ecdsa device not found: %d\n", ret);
		return CMD_RET_FAILURE;
	}

	ops = device_get_ops(ecdsa_dev);

	ret = ops->verify(ecdsa_dev, &pubkey, hash, sizeof(hash), sig, sizeof(sig));
	if (ret) {
		printf("MC_ECDSA384_SIG_VERIFY positive case FAIL (expected PASS): %d\n", ret);
		return CMD_RET_FAILURE;
	}
	printf("MC_ECDSA384_SIG_VERIFY positive case: PASS (agrees with the Cmk-based signature)\n");

	memcpy(bad_hash, hash, sizeof(hash));
	bad_hash[0] ^= 0xff;

	ret = ops->verify(ecdsa_dev, &pubkey, bad_hash, sizeof(bad_hash), sig, sizeof(sig));
	if (ret == 0) {
		printf("MC_ECDSA384_SIG_VERIFY negative case FAIL (tampered digest accepted!)\n");
		return CMD_RET_FAILURE;
	}
	printf("MC_ECDSA384_SIG_VERIFY negative case: PASS (tampered digest correctly rejected)\n");

	return CMD_RET_SUCCESS;
}

